import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { notes, type LocalNote } from "../src/content/notes";
import { parseCsv } from "../src/features/auth/csv";

const args = process.argv.slice(2);
const option = (name: string, fallback: string) => {
  const index = args.indexOf(name);
  if (index < 0) return fallback;
  const value = args[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`Missing ${name}`);
  return value;
};
const parsed = parseCsv(
  readFileSync(
    option("--manifest", "artifacts/materials/import-manifest.csv"),
    "utf8",
  ).replace(/^\uFEFF/, ""),
);
const header = parsed.shift() ?? [];
const rows = parsed.map((cells) =>
  Object.fromEntries(header.map((key, i) => [key, cells[i] ?? ""])),
);
const approved = rows.filter(
  (r) =>
    r.approved?.toLowerCase() === "yes" &&
    r.text_reviewed?.toLowerCase() === "yes",
);
if (!approved.length)
  throw new Error(
    "No reviewed text selected. Set approved=yes and text_reviewed=yes after checking content, course order and sharing permission.",
  );
const result = new Map(notes.map((n) => [n.id, n]));
for (const row of approved) {
  if (
    !/^[a-f0-9]{64}$/.test(row.sha256 ?? "") ||
    /exclude-|exact-duplicate/.test(row.review_flags ?? "")
  )
    throw new Error("Invalid or excluded source row.");
  if (
    !row.program_id ||
    !row.course_code ||
    !/^[0-8]$/.test(row.semester ?? "") ||
    !row.credit_line ||
    !row.sharing_permission ||
    !["book", "notes"].includes(row.kind ?? "")
  )
    throw new Error(`Complete course mapping and permission: ${row.title}`);
  const sequence = Number(row.sequence);
  if (!Number.isSafeInteger(sequence) || sequence < 1)
    throw new Error(`Invalid sequence: ${row.title}`);
  const draft = JSON.parse(
    readFileSync(
      join(option("--drafts", "artifacts/text-notes"), `${row.sha256}.json`),
      "utf8",
    ),
  ) as {
    id: string;
    pageCount?: number;
    pages: {
      no: number;
      text: string;
      method: string;
      needsOcr: boolean;
      hasImages: boolean;
    }[];
  };
  if (
    draft.id !== row.sha256 ||
    !draft.pages.length ||
    (draft.pageCount !== undefined && draft.pages.length !== draft.pageCount) ||
    draft.pages.some((p, i) => p.no !== i + 1) ||
    draft.pages.some((p) => p.needsOcr || typeof p.text !== "string")
  )
    throw new Error(`Unfinished OCR: ${row.title}`);
  const entry: LocalNote = {
    id: draft.id,
    title: row.title!,
    filename: row.relative_path!.split("/").pop()!,
    kind: row.kind as "book" | "notes",
    programId: row.program_id,
    courseCode: row.course_code,
    courseTitle: row.course_title || row.course_code,
    semester: Number(row.semester),
    sequence,
    creditLine: row.credit_line,
    pages: draft.pages.map(({ no, text, method, hasImages }) => ({
      no,
      text,
      method,
      hasImages,
    })),
  };
  if (
    [...result.values()].some(
      (n) =>
        n.id !== entry.id &&
        n.courseCode === entry.courseCode &&
        n.sequence === entry.sequence,
    )
  )
    throw new Error(`Duplicate lecture sequence: ${row.title}`);
  result.set(entry.id, entry);
}
const javascript =
  "// Reviewed offline content. Generated by scripts/publish-local-notes.ts.\nexport const notes = " +
  JSON.stringify([...result.values()]) +
  ";\n";
if (Buffer.byteLength(javascript) > 2 * 1024 * 1024)
  throw new Error(
    "This pack exceeds the 2 MiB text budget. Split into separate content packs before bundling more material.",
  );
if (args.includes("--write")) {
  writeFileSync("src/content/notes.js", javascript, "utf8");
  console.log(
    `Published ${approved.length} reviewed local entries. Rebuild the app to distribute updated offline content.`,
  );
} else
  console.log(
    `Preview only: ${approved.length} reviewed entries; ${Buffer.byteLength(javascript)} bytes. Add --write to generate src/content/notes.js.`,
  );
